-- bnktest_try 資料表（PostgreSQL / H2(PostgreSQL mode) 共用）
-- DDL 獨立版控，與程式分開審核

CREATE TABLE IF NOT EXISTS COMPANY_ACCOUNT
(
    COMPANY_ID     VARCHAR(10) NOT NULL,  -- 企業統編
    ACCOUNT_NO   VARCHAR(17) NOT NULL,  -- 帳號
    AREA      VARCHAR(2)  NOT NULL,  -- 地區 TW/HK/SG/VN
    CURRENCY      VARCHAR(3)  NOT NULL,  -- 幣別
    ACCOUNT_TYPE VARCHAR(10) NOT NULL,  -- 活存 / 定存 / 外存
    CONSTRAINT PK_COMPANY_ACCOUNT PRIMARY KEY (COMPANY_ID, ACCOUNT_NO)
);

CREATE TABLE IF NOT EXISTS ACCOUNT_ALIAS
(
    COMPANY_ID   VARCHAR(10) NOT NULL,
    ACCOUNT_NO VARCHAR(17) NOT NULL,
    ALIAS   VARCHAR(15) NOT NULL,   -- 使用者自訂帳號暱稱
    CONSTRAINT PK_ACCOUNT_ALIAS PRIMARY KEY (COMPANY_ID, ACCOUNT_NO)
);
